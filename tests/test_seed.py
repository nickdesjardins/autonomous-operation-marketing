"""The sample inventory and the SQL rendered from it.

``sql/init_inventory.sql`` is generated, so the committed file is compared with the generator:
an edit to one without the other fails here, before docker-compose and the service disagree.
"""

from __future__ import annotations

import re

from app.schemas import SkuRecord
from app.seed import (
    SAMPLE_ANGLES,
    SKU_SEED,
    SQL_PATH,
    _sql_text,
    main,
    render_sql,
    schema_statements,
    seed_records,
    seed_statements,
)


def test_the_committed_sql_file_matches_the_generator() -> None:
    assert SQL_PATH.name == "init_inventory.sql"
    assert SQL_PATH.read_text(encoding="utf-8") == render_sql()


def test_seed_records_validate_and_describe_four_products() -> None:
    records = seed_records()
    assert len(records) == len(SKU_SEED) == 4
    assert all(isinstance(record, SkuRecord) for record in records)
    assert len({record.sku_code for record in records}) == 4
    assert len({record.npn_number for record in records}) == 4
    assert all(record.authorized_claims for record in records)
    assert all(record.active_ingredients for record in records)
    assert all(ingredient.amount > 0 for r in records for ingredient in r.active_ingredients)


def test_exactly_one_sku_is_out_of_stock() -> None:
    out = [record.sku_code for record in seed_records() if record.stock_quantity == 0]
    assert out == ["NR-VITD-1000"]


def test_every_npn_has_eight_digits() -> None:
    for record in seed_records():
        assert re.fullmatch(r"\d{8}", record.npn_number), record.sku_code


def test_mandatory_statements_exist_for_every_in_stock_sku() -> None:
    for record in seed_records():
        if record.stock_quantity > 0:
            assert any(statement.mandatory for statement in record.risk_information), (
                record.sku_code
            )


def test_rendered_sql_is_idempotent_and_escapes_quotes() -> None:
    statements = seed_statements()
    assert len(statements) == 4
    assert all("ON CONFLICT (sku_code) DO UPDATE" in statement for statement in statements)
    assert all(statement.endswith("updated_at = now();") for statement in statements)
    assert all("::jsonb" in statement for statement in statements)
    vitamin_d = next(statement for statement in statements if "'NR-VITD-1000'" in statement)
    assert ", NULL, " in vitamin_d  # no contraindications: SQL NULL, not the text "None"
    assert _sql_text("O'Brien's") == "'O''Brien''s'" and _sql_text(None) == "NULL"
    ddl = schema_statements()
    assert [part.split("(")[0].strip() for part in ddl if part.startswith("CREATE TABLE")] == [
        "CREATE TABLE IF NOT EXISTS inventory_skus",
        "CREATE TABLE IF NOT EXISTS webhook_audit_log",
        "CREATE TABLE IF NOT EXISTS webhook_inbox",
    ]
    text = render_sql()
    assert text.startswith("-- Generated by `python -m app.seed`")
    assert text.count("INSERT INTO inventory_skus") == 4
    assert "\u2014" not in text
    assert text.endswith("\n")


def test_the_command_line_prints_or_writes(capsys, tmp_path, monkeypatch) -> None:
    assert main(["--print"]) == 0
    assert capsys.readouterr().out == render_sql()
    target = tmp_path / "sql" / "init_inventory.sql"
    monkeypatch.setattr("app.seed.SQL_PATH", target)
    assert main([]) == 0
    assert target.read_bytes() == render_sql().encode("utf-8")  # LF line endings on every host
    assert str(target) in capsys.readouterr().out


def test_sample_angles_are_short_plain_briefs() -> None:
    assert len(SAMPLE_ANGLES) >= 3
    for angle in SAMPLE_ANGLES:
        assert 10 <= len(angle) <= 300 and "\u2014" not in angle
